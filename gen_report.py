# ── Helpers ───────────────────────────────────────────────────────────────────

def set_arial(run, bold=False, size=12):
    run.font.name  = 'Arial'
    run.font.size  = Pt(size)
    run.font.bold  = bold
    rPr = run._r.get_or_add_rPr()
    rFonts = OxmlElement('w:rFonts')
    rFonts.set(_qn('w:ascii'), 'Arial')
    rFonts.set(_qn('w:hAnsi'), 'Arial')
    rFonts.set(_qn('w:cs'),    'Arial')
    rPr.insert(0, rFonts)


def para(text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False, size=12,
         space_before=0, space_after=6, indent=False):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after  = Pt(space_after)
    if indent:
        pf.first_line_indent = Cm(1.25)
    pf.line_spacing = Pt(18)   # 1.5 * 12
    r = p.add_run(text)
    set_arial(r, bold=bold, size=size)
    return p


def heading(text, level=1):
    sizes  = {1: 14, 2: 12, 3: 12}
    before = {1: 18, 2: 12, 3: 6}
    sz     = sizes.get(level, 12)
    sb     = before.get(level, 6)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER   # все заголовки по центру
    p.paragraph_format.space_before = Pt(sb)
    p.paragraph_format.space_after  = Pt(6)
    p.paragraph_format.line_spacing = Pt(18)
    r = p.add_run(text)
    set_arial(r, bold=True, size=sz)
    return p


def bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after  = Pt(3)
    p.paragraph_format.line_spacing = Pt(18)
    r = p.add_run(text)
    set_arial(r, size=12)
    return p


